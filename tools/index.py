#!/usr/bin/env python3
"""Cross-mission index. usage: index.py OUT.md REPO_URL=LEDGER.json [REPO_URL=LEDGER.json ...]
Each mission's standing line, open gaps and last cycle date, grouped by domain taken from the repository name."""
import json, sys

OPEN_GAP = {"proposed", "in_cycle", "immovable"}


def line(url, path):
    L = json.load(open(path)); m = L["missions"][0]
    fs = [f for f in L["findings"] if f.get("audience", "briefing") == "briefing"]
    n = {k: sum(f["standing"]["status"] == k for f in fs) for k in ("certified", "accepted", "refuted")}
    gaps = [g for g in L["gaps"] if g.get("audience", "briefing") == "briefing" and g["status"] in OPEN_GAP]
    last = max((str(c["dated"]) for c in L["cycles"]), default="")
    name = url.rstrip("/").split("/")[-1]
    domain = name.split("-")[1] if name.count("-") >= 2 else "other"
    first_ask = sorted(gaps, key=lambda g: g["priority"])[0]["title"] if gaps else ""
    return domain, f"| [{name}]({url}) | {m['title']} | {m.get('kind', '')} | {n['certified']} | {n['accepted']} | {n['refuted']} | {len(gaps)} | {last} | {first_ask} |"


def main(argv):
    out, pairs = argv[0], [a.split("=", 1) for a in argv[1:]]
    rows = {}
    for url, path in pairs:
        d, r = line(url, path); rows.setdefault(d, []).append(r)
    text = ["# DEBRIEF register — index", "", "Generated by `tools/index.py` from each mission's ledger. Standing words are defined in `schema/SCHEMA.md`. An open gap is not a finding and has no standing.", ""]
    for d in sorted(rows):
        text += [f"## {d}", "", "| repository | mission | kind | certified | accepted | refuted | open gaps | last cycle | first ask |", "|---|---|---|---|---|---|---|---|---|"] + rows[d] + [""]
    open(out, "w").write("\n".join(text)); print(f"wrote {out}: {sum(len(v) for v in rows.values())} missions")


if __name__ == "__main__":
    main(sys.argv[1:])
