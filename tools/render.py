#!/usr/bin/env python3
"""Render a DEBRIEF ledger into human-readable and spoken forms.

usage: render.py LEDGER.json --scorecard OUT.md | --spoken OUT.md | --asks OUT.md

scorecard: standing table, replay (cycles in order), gaps in priority order, corrections.
spoken:    the briefing knowledge base (briefing-audience items only; no record mechanics).
asks:      one section per open gap with what closes it, who could act, the contribution kind, expected signal
           and resolution date. This is the contribution surface of a mission repository.
"""
import json, sys

OPEN_GAP = {"proposed", "in_cycle", "immovable"}
CONTRIB = {"rerun": "rerun", "read": "read", "data_release": "data", "measurement": "data", "research": "claim or research", "decision": "decision by the named party"}


def briefing(docs):
    return [d for d in docs if d.get("audience", "briefing") == "briefing"]


def counts(L):
    fs = briefing(L["findings"])
    n = {k: sum(f["standing"]["status"] == k for f in fs) for k in ("certified", "accepted", "refuted")}
    n_open = sum(g["status"] in OPEN_GAP for g in briefing(L["gaps"]))
    return f"Certified {n['certified']}. Accepted {n['accepted']}. Refuted {n['refuted']}. Open gaps {n_open}."


def scorecard(L):
    m = L["missions"][0]
    out = [f"# {m['title']}", "", m["short_version"]["spoken"], "", "_Rendered from the briefing record. Items marked internal in the ledger (how the framework works, the state of the record) stay in `ledger.json` and are not shown here._", "", f"Record quality: {m['record_quality'].replace('_', ' ')}. {m.get('record_note', '')}".strip(), "",
           f"**Standing.** {counts(L)} An open gap is an input or question nobody has settled; it is not a finding and has no standing.", "",
           "## Findings", "", "| id | kind | standing | basis | cycles |", "|---|---|---|---|---|"]
    for f in briefing(L["findings"]):
        out.append(f"| {f['finding_id']} | {f['kind']} | **{f['standing']['status']}** | {f['standing'].get('basis', '')} | {', '.join(str(c) for c in f['evidence'].get('cycles', []))} |")
    out += ["", "## Cycles, in order", "", "| cycle | dated | by | kind | written first | verdict |", "|---|---|---|---|---|---|"]
    for c in briefing(L["cycles"]):
        pre = c["preregistered"]
        first = "yes" if pre.get("before_data") is True else ("no" if pre.get("before_data") is False else "unknown")
        out.append(f"| {c['cycle']} | {c['dated']} | {c.get('by', '')} | {c.get('kind', '')} | {first} | {c['outcome']['verdict']} |")
    out += ["", "## Gaps, in the order that would settle things fastest", "", "| priority | gap | status | closes with | who could act | signal expected | resolution by |", "|---|---|---|---|---|---|---|"]
    for g in sorted(briefing(L["gaps"]), key=lambda g: g["priority"]):
        cw = "; ".join(c["what"] for c in g["closes_with"])
        who = "; ".join(c.get("who_could_act", "") for c in g["closes_with"] if c.get("who_could_act"))
        out.append(f"| {g['priority']} | {g['title']} | {g['status'].replace('_', ' ')} | {cw} | {who} | {g.get('expected_signal', '')} | {g.get('resolution_by', '')} |")
    corr = [f for f in briefing(L["findings"]) if f["kind"] in ("correction", "retracted", "ruled_out")]
    if corr:
        out += ["", "## Corrections, retractions, ruled out", ""] + [f"- **{f['finding_id']}** ({f['kind']}): {f['spoken']}" for f in corr]
    out += ["", f"_Generated by DEBRIEF tools/render.py from ledger.json; protocol {m.get('protocol_version', '0.1.0')}._", ""]
    return "\n".join(out)


def spoken(L):
    m = L["missions"][0]
    cycles, findings, gaps = briefing(L["cycles"]), briefing(L["findings"]), sorted(briefing(L["gaps"]), key=lambda g: g["priority"])
    say = lambda f: f["spoken"] + f" Standing: {f['standing']['status']}. Basis: {f['standing'].get('basis', '')}.\n"
    out = [f"# Knowledge base (generated from the DEBRIEF ledger) — {m['title']}", "", "Limits: " + " ".join(m.get("scope_limits", [])), "",
           "## The short version", "", m["short_version"]["spoken"], "", "## What happened", "", m.get("what_happened", {}).get("spoken", ""), ""]
    if cycles:
        out += ["## Cycle by cycle", ""] + [c["spoken"] + "\n" for c in cycles]
    out += ["## What was learned", ""] + [say(f) for f in findings if f["kind"] in ("learned", "discovery")]
    other = [f for f in findings if f["kind"] not in ("learned", "discovery")]
    if other:
        out += ["## Retracted, ruled out, and corrected", ""] + [say(f) for f in other]
    out += ["## Standing of the findings", "", counts(L) + " An open gap is an input or question nobody has settled yet; it is not a finding and has no standing.", "",
            "## What was escalated, and what gaps still exist", ""]
    for g in gaps:
        hist = " ".join(f"In cycle {h['cycle']}, the hypothesis was {h['hypothesis']}: {h['result']}." for h in g.get("history", []))
        out.append(f"{g['title']}. Status: {g['status'].replace('_', ' ')}. {g['spoken']} {hist}".strip() + "\n")
    out += ["## Outstanding anomalies", ""] + [a["spoken"] + f" Status: {a['status']}.\n" for a in L["anomalies"]]
    out += ["## What needs your attention", ""] + [f"{g['ask']['spoken']}\n" for g in gaps if g["status"] in OPEN_GAP]
    imp = m.get("implications", {})
    if imp:
        out += ["## What this changes", ""]
        for k, label in (("rely_on", "Rely on"), ("do_not_rely_on", "Do not rely on"), ("stop", "Stop"), ("new", "New")):
            for item in imp.get(k, []):
                if item.get("audience", "briefing") == "briefing":
                    out.append(f"{label}: {item['spoken']}\n")
    out += ["## Background", ""] + [f"{b['term']}. {b['spoken']}\n" for b in L["background"]]
    return "\n".join(out)


def asks(L):
    m = L["missions"][0]
    out = [f"# Asks — {m['title']}", "", "Each open gap below is a place a contribution can land. A contribution is one cycle in this repository's ledger, under your name. How to contribute, and the templates: https://github.com/Nervous-Machine/DEBRIEF/blob/main/CONTRIBUTING.md", ""]
    for g in sorted(briefing(L["gaps"]), key=lambda g: g["priority"]):
        if g["status"] not in OPEN_GAP:
            continue
        out += [f"## {g['priority']}. {g['title']}", "", g["spoken"], "", f"Status: {g['status'].replace('_', ' ')}.", ""]
        for c in g["closes_with"]:
            out.append(f"- **{c['what']}** — contribution kind: {CONTRIB.get(c['kind'], c['kind'])}; who could act: {c.get('who_could_act', 'anyone')}.")
        out += ["", f"Signal expected: {g.get('expected_signal') or 'not yet registered'}. Resolution by: {g.get('resolution_by') or 'none registered'}.", ""]
    return "\n".join(out)


if __name__ == "__main__":
    a = sys.argv[1:]
    if len(a) != 3 or a[1] not in ("--scorecard", "--spoken", "--asks"):
        print(__doc__); sys.exit(2)
    L = json.load(open(a[0]))
    text = {"--scorecard": scorecard, "--spoken": spoken, "--asks": asks}[a[1]](L)
    open(a[2], "w").write(text)
    print(f"wrote {a[2]} ({len(text.splitlines())} lines)")
